"""Bundle the SDK's sidecar loop + ``report_pack.py`` into ONE file: ``plugin.py``.

The Tier-1 artifact is a single ``plugin.py`` (the manifest's ``wasm_url``
points at it) and the Python SDK is not on PyPI, so the host has nothing to
``import hellohq_plugin_sdk`` from. This concatenates, in order:

  1. ``sdks/python/hellohq_plugin_sdk/protocol.py``  (constants, PluginError)
  2. ``sdks/python/hellohq_plugin_sdk/sidecar.py``   (the NDJSON ``serve`` loop)
  3. ``report_pack.py``                              (this plugin)

with their ``hellohq_plugin_sdk`` imports and ``from __future__`` lines removed
(one ``from __future__`` line is hoisted to the top). Only those two SDK
modules are bundled: Report Pack makes no host call, so ``host.py`` and the
propose modules stay out.

The output is a pure function of those three files (no timestamps, no paths),
so two builds produce identical bytes. ``tests/test_bundle.py`` checks that,
and that the result imports only the standard library.

Usage: python3 bundle.py [out_path]   (default: plugin.py next to this file)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SDK = HERE.parent.parent / "sdks" / "python" / "hellohq_plugin_sdk"
SOURCES = [
    ("hellohq_plugin_sdk/protocol.py", SDK / "protocol.py"),
    ("hellohq_plugin_sdk/sidecar.py", SDK / "sidecar.py"),
    ("report_pack.py", HERE / "report_pack.py"),
]

# ``from .protocol import (...)`` / ``from hellohq_plugin_sdk.x import y``,
# single-line or parenthesised.
_SDK_IMPORT = re.compile(r"^from (\.[\w.]*|hellohq_plugin_sdk[\w.]*) import ")
_FUTURE = "from __future__ import annotations"


def _strip(source: str, name: str) -> str:
    out: list[str] = []
    skipping = False
    # Split on line feeds only: str.splitlines() also splits on U+2028, U+2029,
    # \x0b, \x0c, \x1c-\x1e and \x85, which this plugin's source holds inside
    # string literals (the text-sanitising code); joining on "\n" would break them.
    for line in source.replace("\r\n", "\n").split("\n"):
        if skipping:
            skipping = line.strip() != ")"
            continue
        if line.strip() == _FUTURE:
            continue
        if _SDK_IMPORT.match(line):
            skipping = line.rstrip().endswith("(")
            continue
        out.append(line)
    if skipping:
        raise SystemExit(f"bundle: {name}: unterminated parenthesised import")
    return "\n".join(out).strip("\n")


def build() -> str:
    parts = [
        '"""Report Pack: single-file Tier-1 sidecar (generated by bundle.py; do not edit).',
        "",
        "Source: examples/report-pack in https://github.com/HelloHQ/plugin-sdk",
        '"""',
        "",
        _FUTURE,
    ]
    for label, path in SOURCES:
        parts += ["", "", f"# ---- {label} " + "-" * (60 - len(label)), ""]
        parts.append(_strip(path.read_text(encoding="utf-8"), label))
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "plugin.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n": identical bytes on every OS.
    out.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")
